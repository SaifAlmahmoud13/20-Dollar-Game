#!/usr/bin/env node
// Writes dist/sw.js: a service worker that stores every file of the built game on the
// phone at first visit, so it then opens and plays with no internet. The cache name
// includes a hash of the files, so each new deploy replaces the old copy.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const DIST = path.join(path.dirname(path.dirname(fileURLToPath(import.meta.url))), 'dist');

const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const full = path.join(dir, name);
    if (statSync(full).isDirectory()) walk(full);
    else if (name !== 'sw.js' && !name.startsWith('.')) files.push(path.relative(DIST, full).split(path.sep).join('/'));
  }
})(DIST);
files.sort();

const hash = createHash('sha256');
for (const f of files) hash.update(f).update(readFileSync(path.join(DIST, f)));
const version = hash.digest('hex').slice(0, 12);

const sw = `// Generated by scripts/write-sw.mjs
const CACHE = 'twenty-dollar-${version}';
const FILES = ${JSON.stringify(['./', ...files], null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('twenty-dollar-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

// Pages: the newest version from the internet when online (so updates show up straight
// away), the stored copy when offline. Everything else (code, photos, sounds, which have
// unique names per version): the stored copy first, else the internet (and keep a copy).
self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;
  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request)
        .then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(CACHE).then((cache) => cache.put('./', copy));
          }
          return res;
        })
        .catch(() => caches.match('./')),
    );
    return;
  }
  event.respondWith(
    caches.match(request, { ignoreSearch: true }).then((hit) => {
      if (hit) return hit;
      return fetch(request).then((res) => {
        if (res.ok) {
          const copy = res.clone();
          caches.open(CACHE).then((cache) => cache.put(request, copy));
        }
        return res;
      });
    }),
  );
});
`;
writeFileSync(path.join(DIST, 'sw.js'), sw);
console.log(`dist/sw.js: ${files.length + 1} files cached (version ${version})`);
